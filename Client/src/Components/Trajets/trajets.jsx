const renderIcon = (type, level) => {
  let iconPath = "";
  let alt = "";

  switch (level) {
    case 1:
      iconPath = `./icon/${type}-no.svg`;
      alt = `${type} : non`;
      break;
    case 2:
      iconPath = `./icon/${type}-neutral.svg`;
      alt = `${type} : indifférent`;
      break;
    case 3:
      iconPath = `./icon/${type}-yes.svg`;
      alt = `${type} : oui`;
      break;
    default:
      iconPath = `./icon/${type}-unknown.svg`;
      alt = `${type} : inconnu`;
  }

  return (
    <div className="modal-option-icon">
      <img src={iconPath} alt={alt} />
    </div>
  );
};

